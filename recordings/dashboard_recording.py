import re
from playwright.sync_api import Page, expect


def test_example(page: Page) -> None:
    page.goto("https://demoblaze.com/")
    page.get_by_role("link", name="Sign up").click()
    page.get_by_role("textbox", name="Username:").click()
    page.get_by_role("textbox", name="Password:").click()
    page.once("dialog", lambda dialog: dialog.dismiss())
    page.get_by_role("button", name="Sign up").click()
    page.get_by_role("dialog", name="Sign up").get_by_label("Close").click()
    page.get_by_role("link", name="Sign up").click()
    page.get_by_role("textbox", name="Username:").click()
    page.get_by_role("textbox", name="Username:").fill("nazmussakib1302")
    page.get_by_role("textbox", name="Password:").click()
    page.get_by_role("textbox", name="Password:").fill("sakib1302")
    page.once("dialog", lambda dialog: dialog.dismiss())
    page.get_by_role("button", name="Sign up").click()
    page.get_by_role("link", name="Log in").click()
    page.locator("#loginusername").click()
    page.locator("#loginusername").fill("nazmussakib1302")
    page.get_by_role("dialog", name="Log in").click()
    page.locator("#loginpassword").click()
    page.locator("#loginpassword").fill("sakib131")
    page.once("dialog", lambda dialog: dialog.dismiss())
    page.get_by_role("button", name="Log in").click()
    page.locator("#loginpassword").click()
    page.locator("#loginpassword").fill("sakib132")
    page.once("dialog", lambda dialog: dialog.dismiss())
    page.get_by_role("button", name="Log in").click()
    page.locator("#loginpassword").click()
    page.locator("#loginpassword").fill("sakib1302")
    page.locator("#loginpassword").press("Enter")
    page.get_by_role("button", name="Log in").click()
    page.get_by_role("link", name="Welcome nazmussakib1302").click()
    expect(page.locator("#nameofuser")).to_contain_text("Welcome nazmussakib1302")
